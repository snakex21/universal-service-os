#!/usr/bin/env python3
"""Generate src/compat/win3x/display_table.zig: the display driver patch plans
that the micro-Linux tool (usos-fb-ui --win3x-display) applies.

Copyright (C) 2026 Maksymilian and the USOS Authors. GPL-3.0-or-later.

tools/win3x_vga_patch.py (capstone walk) decides, per driver, which
instruction windows become a near CALL to a stub. The micro-Linux has no
Python or capstone, so this script records only that decision for each
known driver: the input sha256, the windows (segment, start, instruction
lengths, which of them is the XCHG), the site count and the sha256 of the
patched file. The Zig tool rebuilds the stubs and the file layout from the
user's own driver and writes the result only when its sha256 equals the
recorded one. The table holds offsets, lengths and hashes, no bytes of the
drivers.

    python tools/win3x_patch_table.py "3.1 VGA.DRV=path/VGA.DRV" ... > src/compat/win3x/display_table.zig
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import win3x_vga_patch as vp  # noqa: E402


def plan(raw: bytes):
    out, sites, reach = vp.patch(raw)
    ne = vp.parse_ne(raw)
    windows = []
    for seg in ne.segments:
        todo = [s for s in sites if s.seg == seg.index and s.action == 'patched']
        if not todo:
            continue
        insns = reach[seg.index][0]
        kinds = {s.off: s.kind for s in sites if s.seg == seg.index and s.window}
        for s in todo:
            lo, hi = s.window
            parts, k = [], lo
            while k < hi:
                size = insns[k].size
                if k in kinds and kinds[k] != 'xchg':
                    raise SystemExit('only XCHG plans are supported by the Zig tool')
                parts.append(size | (0x80 if k in kinds else 0))
                k += size
            windows.append((seg.index, lo, parts))
    return out, windows, len(vp.replaced(sites))


def main(argv):
    if not argv:
        print(__doc__, file=sys.stderr)
        return 2
    print('//! Generated by tools/win3x_patch_table.py from the drivers named below')
    print('//! (tools/win3x_vga_patch.py decides the sites). Offsets, lengths and')
    print('//! hashes only; see src/compat/win3x/display_patch.zig.')
    print('const Plan = @import("display_patch.zig").Plan;')
    print('const hex = @import("display_patch.zig").hex;')
    print('')
    print('pub const plans = [_]Plan{')
    for arg in argv:
        label, _, path = arg.partition('=')
        raw = Path(path).read_bytes()
        out, windows, n = plan(raw)
        print('    .{')
        print(f'        .label = "{label}",')
        print(f'        .input = hex("{hashlib.sha256(raw).hexdigest()}"),')
        print(f'        .output = hex("{hashlib.sha256(out).hexdigest()}"),')
        print(f'        .output_len = {len(out)},')
        print(f'        .sites = {n},')
        print('        .windows = &.{')
        for seg, lo, parts in windows:
            p = ', '.join(f'0x{x:02X}' for x in parts)
            print(f'            .{{ .seg = {seg}, .lo = 0x{lo:04X}, .parts = &.{{{p}}} }},')
        print('        },')
        print('    },')
    print('};')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
