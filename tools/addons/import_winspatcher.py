"""Turn a WinSPatcher update set (Inno Setup, G. Skulimowski, freeware) into
manifest hotfix packages of the legacy compatibility pack.

WinSPatcher's own list (app\\wpsetup.dat, cp1250) names every update with
its silent command line, in install order. This tool extracts the set with
innoextract (tools/cache/innoextract, pinned in the build kit), keeps the
security/critical updates ([Instal_AK], [Instal_A]) that the manifest does
not already carry (same SHA-256 = duplicate), unwraps WinSPatcher's own
wrapper (wpaicc.exe "name=path cmd"), and writes one tier=none package per
update plus a group, between generated markers in src/addons/legacy-pack.ini:

  ; >>> generated by tools/addons/import_winspatcher.py: <group>
  ...
  ; <<< <group>

The files stay the user's (source=user): each points into the WinSPatcher
executable as container!app/<path>, found by SHA-256 when staging.
Copyright (C) 2026 Maksymilian and the USOS Authors, GPL-3.0-or-later.

  python tools/addons/import_winspatcher.py --exe WinSPatcher_NT_v1.0.exe --group hotfixes-nt4-pl
"""
from __future__ import annotations

import argparse
import hashlib
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import legacy_manifest as lm  # noqa: E402
from stage_legacy_pack import innoextract_tool  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]

# What each known set becomes. skip: items the manifest covers otherwise or
# that are not updates (GDI+ detection tool needs the web; Windows Update
# client pieces are useless offline).
SETS = {
    'hotfixes-nt4-pl': {
        'title_pl': 'Poprawki zabezpieczeń Windows NT 4.0 po SRP (WinSPatcher NT)',
        'title_en': 'Windows NT 4.0 post-SRP security updates (WinSPatcher NT, Polish)',
        'os': 'NT4', 'lang': 'PL', 'ntsp': '6a+', 'needs': ['ntsp:6a'], 'order': 940, 'prefix': 'hfnt',
        'skip': re.compile(r'(?i)polq299444i|dotnetfx|kb867460|langpack|873374|msjavwu'),
        'needs_by_file': {r'(?i)^ie|kb867801|kb823353': 'ie:6.0'},
    },
    'hotfixes-98-pl-extra': {
        'title_pl': 'Dodatkowe poprawki Windows 98 (WinSPatcher 98)',
        'title_en': 'Additional Windows 98 (first edition) updates (WinSPatcher 98, Polish)',
        'os': '98FE', 'lang': 'PL', 'ntsp': '', 'needs': [], 'order': 945, 'prefix': 'hf98x',
        'skip': re.compile(r'(?i)873374|^wu\.exe|wucsp'),
        'needs_by_file': {r'(?i)^ie|oe6': 'ie:6.0', r'(?i)wm320920_71|windowsmedia71': 'wmp:7.1'},
    },
}


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def read_dat(path: Path) -> dict[str, list[tuple[str, str]]]:
    sections: dict[str, list[tuple[str, str]]] = {}
    cur = None
    for line in path.read_bytes().decode('cp1250').replace('\r', '').split('\n'):
        if line.startswith('['):
            cur = line.strip('[] ')
            sections[cur] = []
        elif cur and '=' in line and not line.startswith(';'):
            name, cmd = line.split('=', 1)
            sections[cur].append((name.strip(), cmd.strip()))
    return sections


def unwrap(folder: str, cmd: str) -> tuple[str, str]:
    """(relative file, switches) from a wpsetup.dat command."""
    m = re.match(r'(?i)wpaicc\.exe\s+"[^=]*=(\S+)\s*(.*)"$', cmd)
    if m:
        return m.group(1).replace('\\', '/'), m.group(2).strip()
    first, _, rest = cmd.partition(' ')
    return f'{folder}/{first}', rest.strip()


def short_name(file: str, used: set[str]) -> str:
    stem = re.sub(r'[^A-Z0-9]', '', Path(file).stem.upper())
    kb = re.search(r'(?:KB|Q)?(\d{6})', Path(file).stem.upper())
    base = (('Q' + kb.group(1)) if kb else stem)[:8] or 'HOTFIX'
    if base in used and len(base) == 7:
        base = base[:1] + 'X' + base[1:]  # Q870669 -> QX870669
    name, n = base, 1
    while name in used:
        name = base[:6] + f'{n:02d}'
        n += 1
    used.add(name)
    return name


def build(exe: Path, group: str, manifest: Path) -> str:
    spec = SETS[group]
    m = lm.Manifest.load(manifest)
    known = {f['sha256'] for p in m.packages if not p.id.startswith(spec['prefix'] + '-') for f in p.files()}
    work = Path(tempfile.mkdtemp(prefix='wsp-'))
    try:
        tool = innoextract_tool()
        if tool is None:
            raise SystemExit('innoextract not found (tools/release/fetch_buildkit_inputs.py)')
        subprocess.run([str(tool), '-q', '-s', '-e', '-d', str(work), str(exe)], check=True)
        app = work / 'app'
        dat = read_dat(app / 'wpsetup.dat')
        items = [('upd_c', n, c) for n, c in dat.get('Instal_AK', [])] + [('upd_s', n, c) for n, c in dat.get('Instal_A', [])]
        used = {p.get('dir').upper() for p in m.packages if not p.id.startswith(spec['prefix'] + '-') and p.get('dir')}
        out, members = [], []
        order = spec['order']
        for folder, title, cmd in items:
            rel, switches = unwrap(folder, cmd)
            if spec['skip'].search(Path(rel).name):
                continue
            data = (app / rel).read_bytes()
            if sha256(data) in known:
                continue
            name = short_name(rel, used)
            pid = f'{spec["prefix"]}-{name.lower()}'
            needs = list(spec['needs'])
            for pattern, cap in spec['needs_by_file'].items():
                if re.search(pattern, Path(rel).name):
                    needs.append(cap)
            kb = re.search(r'(?i)(?:KB|Q)(\d{6})|(\d{6})', Path(rel).stem)
            hotfix_id = None
            if kb and spec['os'] == 'NT4' and '-m' in switches:
                num = kb.group(1) or kb.group(2)
                hotfix_id = ('KB' if 'KB' in Path(rel).stem.upper() else 'Q') + num
            members.append(pid)
            lines = [f'[pkg:{pid}]', f'name_pl={title}', f'name_en={title}', f'dir={name}',
                     f'os={spec["os"]}', f'lang={spec["lang"]}']
            if spec['ntsp']:
                lines.append(f'ntsp={spec["ntsp"]}')
            lines += ['tier=none', f'order={order}']
            if needs:
                lines.append('needs=' + ','.join(needs))
            lines.append(f'provides={pid}')
            if hotfix_id:
                lines.append(f'check=reg:HKLM\\SOFTWARE\\Microsoft\\Windows NT\\CurrentVersion\\Hotfix\\{hotfix_id}')
            lines += ['reboot=end', f'file1={name}.EXE|{exe.name}!app/{rel}|{sha256(data)}|{len(data)}',
                      f'run1=%PKG%\\{name}.EXE {switches}'.rstrip(), 'source=user', 'redist=conditional',
                      'license=LicenseRef-Microsoft-EULA', f'note=From {exe.name} (wpsetup.dat order and switches).', '']
            out.append('\n'.join(lines))
        head = [f'; >>> generated by tools/addons/import_winspatcher.py: {group}',
                f'[pkg:{group}]', f'name_pl={spec["title_pl"]}', f'name_en={spec["title_en"]}',
                f'os={spec["os"]}', f'lang={spec["lang"]}']
        if spec['ntsp']:
            head.append(f'ntsp={spec["ntsp"]}')
        head += ['tier=group', f'order={spec["order"] + 45}', 'needs=' + ','.join(members),
                 f'note=Group of {len(members)} updates from {exe.name}; duplicates of other packages (same SHA-256) left out.', '']
        return '\n'.join(head) + '\n' + '\n'.join(out) + f'; <<< {group}\n'
    finally:
        shutil.rmtree(work, ignore_errors=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--exe', type=Path, required=True)
    ap.add_argument('--group', choices=sorted(SETS), required=True)
    ap.add_argument('--manifest', type=Path, default=lm.MANIFEST)
    a = ap.parse_args()
    block = build(a.exe, a.group, a.manifest)
    text = a.manifest.read_text(encoding='utf-8')
    start = f'; >>> generated by tools/addons/import_winspatcher.py: {a.group}'
    end = f'; <<< {a.group}\n'
    if start in text:
        i = text.index(start)
        j = text.index(end, i) + len(end)
        text = text[:i] + block + text[j:]
    else:
        text = text.rstrip('\n') + '\n\n' + block
    a.manifest.write_text(text, encoding='utf-8', newline='\n')
    print(f'[PASS] {a.group}: {block.count("[pkg:") - 1} packages written to {a.manifest.name}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
