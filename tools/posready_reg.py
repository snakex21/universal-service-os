"""tools/posready_x470.reg from tools/xp_driver_overlay.py registry_rows() plus
the CriticalDeviceDatabase rows POSReady's minimal FBA database lacks.

The XP path writes these values into Setup's hives; POSReady 2009 has no
text-mode Setup, so C:\\USOS\\POSR\\FIRST.CMD imports the same values with
regedit /s at the first logon in the install VM
(docs/posready-2009-2026-10-10.md).

    python tools/posready_reg.py [--check]
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "tools" / "posready_x470.reg"


# POSReady's CriticalDeviceDatabase is the minimal First Boot Agent one: it
# holds only the devices of the install VM (i440FX, PIIX IDE, no PCI-to-PCI
# bridge). XP's text-mode Setup would add txtsetup.sif's PCI\CC_0604 = pci;
# without it the X470 bridges in front of the SATA controllers get no boot
# driver, GenAHCI never sees its controller and the first real boot stops with
# 0x7B INACCESSIBLE_BOOT_DEVICE (X470, 2026-10-12).
SYSTEM = "4D36E97D-E325-11CE-BFC1-08002BE10318"
KEYBOARD = "4D36E96B-E325-11CE-BFC1-08002BE10318"
MOUSE = "4D36E96F-E325-11CE-BFC1-08002BE10318"
USB = "36FC9E60-C465-11CF-8056-444553540000"
HIDCLASS = "745A17A0-74D3-11D0-B6FE-00A0C90F57DA"
#
# The input chain needs the same: on the first X470 boot (2026-10-12) no
# keyboard or mouse worked. The driver signing policy is "Warn", so every
# server-side PnP install that needs the System/Keyboard/Mouse class installer
# (syssetup.dll, 0x800b0100) or an INF without a catalog (usbxhci.inf) was
# blocked and left for a Found New Hardware wizard nobody can answer without
# input. Only devices with a CriticalDeviceDatabase entry got a driver:
#   PS/2: the ACPI PS/2 devices are children of the LPC bridge (PCI\CC_0601);
#         with no service for it they are never enumerated.
#   USB:  xHCI and the root hub came up (pci#cc_0c0330, usb#root_hub30), but
#         the keyboard and mouse stayed without a driver (no usb#class_03 /
#         usb#composite entry).
# These rows are txtsetup.sif's [HardwareIdsDatabase] lines for the same IDs.
POSREADY_CDD = [
    (r"pci#cc_0604", "pci", SYSTEM),
    (r"pci#cc_0601", "isapnp", SYSTEM),
    (r"pci#cc_0602", "isapnp", SYSTEM),
    (r"*pnp0303", "i8042prt", KEYBOARD),
    (r"*pnp030b", "i8042prt", KEYBOARD),
    (r"ps2_keyboard", "i8042prt", KEYBOARD),
    (r"*pnp0f13", "i8042prt", MOUSE),
    (r"ps2_mouse", "i8042prt", MOUSE),
    (r"usb#composite", "usbccgp", USB),
    (r"usb#class_09", "usbhub", USB),
    (r"usb#class_03&subclass_01&prot_01", "hidusb", HIDCLASS),
    (r"usb#class_03&subclass_01&prot_02", "hidusb", HIDCLASS),
    (r"usb#class_03&subclass_01", "hidusb", HIDCLASS),
    (r"usb#class_03", "hidusb", HIDCLASS),
    (r"hid_device_system_keyboard", "kbdhid", KEYBOARD),
    (r"hid_device_system_mouse", "mouhid", MOUSE),
]


def rows() -> list[tuple[str, str, int, object]]:
    src = (ROOT / "tools" / "xp_driver_overlay.py").read_text(encoding="utf-8")
    start = src.index("def registry_rows():")
    end = src.index("def patch_hive")
    ns: dict = {}
    exec(src[start:end], ns)  # noqa: S102 - our own source, one pure function
    out = ns["registry_rows"]()
    for hw, svc, guid in POSREADY_CDD:
        key = "Control" + "\\" + "CriticalDeviceDatabase" + "\\" + hw
        out += [(key, "Service", 1, svc), (key, "ClassGUID", 1, "{" + guid + "}")]
    return out


def render() -> bytes:
    bs = "\\"
    out = ["REGEDIT4", "",
           "; USOS: the XP x86 X470 driver set (KMDF 1.11, USB3 xHCI backport, GenAHCI) for",
           "; Windows Embedded POSReady 2009, imported by C:" + bs + "USOS" + bs + "POSR" + bs + "FIRST.CMD.",
           "; Generated by tools/posready_reg.py from tools/xp_driver_overlay.py registry_rows().", ""]
    keys: dict[str, list] = {}
    for path, name, typ, value in rows():
        keys.setdefault(path, []).append((name, typ, value))
    for path, values in keys.items():
        out.append("[HKEY_LOCAL_MACHINE" + bs + "SYSTEM" + bs + "CurrentControlSet" + bs + path + "]")
        for name, typ, value in values:
            if typ == 4:
                out.append(f'"{name}"=dword:{value:08x}')
            elif typ == 1:
                out.append(f'"{name}"="' + str(value).replace(bs, bs + bs) + '"')
            elif typ == 2:
                out.append(f'"{name}"=hex(2):' + ",".join(f"{b:02x}" for b in str(value).encode("latin1") + b"\0"))
            else:
                raise ValueError(typ)
        out.append("")
    return "\r\n".join(out).encode("latin1")


if __name__ == "__main__":
    data = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_bytes() == data else 1)
    OUT.write_bytes(data)
