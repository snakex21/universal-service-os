"""tools/posready_x470.reg from tools/xp_driver_overlay.py registry_rows().

The XP path writes these values into Setup's hives; POSReady 2009 has no
text-mode Setup, so C:\\USOS\\POSR\\FIRST.CMD imports the same values with
regedit /s at the first logon in the install VM
(docs/posready-2009-2026-10-10.md).

    python tools/posready_reg.py [--check]
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "tools" / "posready_x470.reg"


def rows() -> list[tuple[str, str, int, object]]:
    src = (ROOT / "tools" / "xp_driver_overlay.py").read_text(encoding="utf-8")
    start = src.index("def registry_rows():")
    end = src.index("def patch_hive")
    ns: dict = {}
    exec(src[start:end], ns)  # noqa: S102 - our own source, one pure function
    return ns["registry_rows"]()


def render() -> bytes:
    bs = "\\"
    out = ["REGEDIT4", "",
           "; USOS: the XP x86 X470 driver set (KMDF 1.11, USB3 xHCI backport, GenAHCI) for",
           "; Windows Embedded POSReady 2009, imported by C:" + bs + "USOS" + bs + "POSR" + bs + "FIRST.CMD.",
           "; Generated by tools/posready_reg.py from tools/xp_driver_overlay.py registry_rows().", ""]
    keys: dict[str, list] = {}
    for path, name, typ, value in rows():
        keys.setdefault(path, []).append((name, typ, value))
    for path, values in keys.items():
        out.append("[HKEY_LOCAL_MACHINE" + bs + "SYSTEM" + bs + "CurrentControlSet" + bs + path + "]")
        for name, typ, value in values:
            if typ == 4:
                out.append(f'"{name}"=dword:{value:08x}')
            elif typ == 1:
                out.append(f'"{name}"="' + str(value).replace(bs, bs + bs) + '"')
            elif typ == 2:
                out.append(f'"{name}"=hex(2):' + ",".join(f"{b:02x}" for b in str(value).encode("latin1") + b"\0"))
            else:
                raise ValueError(typ)
        out.append("")
    return "\r\n".join(out).encode("latin1")


if __name__ == "__main__":
    data = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_bytes() == data else 1)
    OUT.write_bytes(data)
