class Staging(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        (self.tmp / 'pkg/usosvbe').mkdir(parents=True)
        shutil.copy(SYS, self.tmp / 'pkg/usosvbe/usosvbe.sys')
        (self.tmp / 'ls').mkdir()
        (self.tmp / 'out').mkdir()

    def tearDown(self):
        shutil.rmtree(self.tmp)

    def stage(self):
        return run_sh(f'USOS_W2K_DIR="{posix(self.tmp / "pkg")}" usos_w2k_vesa_stage "{posix(self.tmp / "out")}" "{posix(self.tmp / "ls")}"')

    def test_staged_files(self):
        fake = b'MSCF fake framebuf cabinet'
        (self.tmp / 'ls/FRAMEBUF.DL_').write_bytes(fake)
        r = self.stage()
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn(b'VESA staged', r.stdout)
        out = self.tmp / 'out'
        self.assertEqual(sorted(p.name for p in out.iterdir()), ['FRAMEBUF.DL_', 'USOSVBE.SYS', 'VESA.REG', 'vesa.cmd'])
        self.assertEqual((out / 'USOSVBE.SYS').read_bytes(), SYS.read_bytes())
        self.assertEqual((out / 'FRAMEBUF.DL_').read_bytes(), fake)
        self.assertEqual((out / 'VESA.REG').read_bytes().decode('ascii'), GOLDEN_REG)
        raw = bytes(int(x, 16) for x in GOLDEN_REG.split('hex(7):')[1].split('\r')[0].split(','))
        self.assertEqual(raw, b'framebuf\0\0')

    def test_without_framebuf_on_the_source(self):
        r = self.stage()
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn(b'no FRAMEBUF.DL_', r.stdout)
        self.assertFalse((self.tmp / 'out/FRAMEBUF.DL_').exists())
        self.assertTrue((self.tmp / 'out/vesa.cmd').exists())

    def test_missing_miniport_stops(self):
        (self.tmp / 'pkg/usosvbe/usosvbe.sys').unlink()
        r = self.stage()
        self.assertEqual(r.returncode, 1)
        self.assertIn(b'STOP', r.stdout)

    def test_vesa_cmd(self):
        cmd = run_sh('usos_w2k_vesa_cmd').stdout
        self.assertTrue(cmd.endswith(b'\r\n'))
        self.assertNotIn(b'\n', cmd.replace(b'\r\n', b''))
        lines = cmd.decode('ascii').split('\r\n')
        i = lines.index(r'if exist "%SystemRoot%\system32\framebuf.dll" goto vesa')
        self.assertEqual(lines[i + 1], r'if not exist "%USOS_DIR%\FRAMEBUF.DL_" goto novesa')
        self.assertTrue(lines[i + 2].startswith(r'"%SystemRoot%\system32\expand.exe" "%USOS_DIR%\FRAMEBUF.DL_" '))
        self.assertEqual(lines[i + 3], r'if not exist "%SystemRoot%\system32\framebuf.dll" goto novesa')
        vesa = lines.index(':vesa')
        reg = lines.index(r'"%SystemRoot%\regedit.exe" /s "%USOS_DIR%\VESA.REG"')
        self.assertIn(r'if not exist "%SystemRoot%\system32\drivers\usosvbe.sys" goto novesa', lines[vesa:reg])
        self.assertLess(reg, lines.index('call :vgaentry'))
        self.assertLess(lines.index('call :vgaentry'), lines.index(':novesa'))
        # boot.ini: the default entry's ARC path again, with /basevideo; only
        # copied back when the new file still has default= and the entry.
        new = lines.index(r'>> "%USOS_DIR%\boot.ini.new" echo %USOS_ARC%="Windows 2000 [VGA mode]" /fastdetect /basevideo')
        back = lines.index(r'copy /y "%USOS_DIR%\boot.ini.new" "%USOS_BINI%" > nul')
        checks = [l for l in lines[new:back] if l.endswith('|| goto vgafail')]
        self.assertEqual(len(checks), 2)
        self.assertIn('echo timeout=5', lines[new - 1])
        self.assertIn(r'attrib +r +s +h "%USOS_BINI%"', lines)
        self.assertNotIn('VgaSave', cmd.decode())


class Flow(unittest.TestCase):
    def test_wiring(self):
        ntfs = NTFS.read_text(encoding='utf-8')
        self.assertIn('call "%%USOS_DIR%%' + chr(92) * 2 + 'vesa.cmd"', ntfs)
        self.assertIn('usos_w2k_vesa_stage "$setup_dir" "$work/volume/\\$WIN_NT\\$.~LS/I386"', ntfs)
        legacy = LEGACY.read_text(encoding='utf-8')
        self.assertIn('Unattended/vesa-off.txt" ]; then USOS_W2K_VESA=off; else USOS_W2K_VESA=on; fi', legacy)
        self.assertIn('USOS_W2K_DIAG USOS_W2K_VESA', legacy)
        sys.path.insert(0, str(ROOT / 'tools'))
        import build_xp_uefi_csm_trial as builder
        files = builder.w2k_driver_files()
        self.assertEqual(files['usosvbe/usosvbe.sys'], SYS.read_bytes())
        # Nothing Microsoft in the package or the repository.
        self.assertFalse([n for n in files if 'framebuf' in n.lower()])
        self.assertEqual([p for p in (ROOT / 'tools').rglob('framebuf.d*')], [])


