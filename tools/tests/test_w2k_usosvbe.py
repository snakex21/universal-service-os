def parse(text: str) -> dict:
    tables, cur = {}, None
    for line in text.splitlines():
        if not line or line.startswith('#'):
            continue
        if line.startswith('['):
            cur = tables.setdefault(line[1:-1], {})
            continue
        name, _, target = line.partition(' -> ')
        cur[name] = target or None
    return tables


def dump(folder: Path) -> str:
    out = ['# Windows 2000 SP4 i386 export names (W2KPLCMA4.811 CD, I386, expanded),',
           '# generated by tools/tests/test_w2k_usosvbe.py --dump-exports. Names only;',
           '# "name -> target" marks an export forwarder.']
    for key in MODULES:
        path = next(p for p in folder.iterdir() if p.name.lower() == key)
        out.append(f'[{key}]')
        out += [n if t is None else f'{n} -> {t}' for n, t in sorted(pe(path)[0].items())]
    return '\n'.join(out) + '\n'


def posix(p: Path) -> str:
    s = str(p).replace('\\', '/')
    return '/' + s[0].lower() + s[2:] if len(s) > 1 and s[1] == ':' else s


def run_sh(script: str) -> subprocess.CompletedProcess:
    return subprocess.run([SH, '-c', f'. "{posix(STAGE)}"; {script}'], capture_output=True)


class Imports(unittest.TestCase):
    def test_resolves_on_2000_sp4(self):
        tables = parse(FIXTURE.read_text())
        self.assertEqual(sorted(tables), sorted(MODULES))
        _, imports = pe(SYS)
        self.assertEqual(sorted({m.lower() for m, _ in imports}), ['ntoskrnl.exe', 'videoprt.sys'])
        for k in KERNELS:
            for h in HALS:
                view = {'ntoskrnl.exe': (tables[k], []), 'hal.dll': (tables[h], []), 'videoprt.sys': (tables['videoprt.sys'], [])}
                missing = sorted({m for m in (resolve(view, mod, fn) for mod, fn in imports) if m})
                self.assertEqual(missing, [], f'{k}+{h}')

    def test_binary_is_the_nt4_build(self):
        # The flow ships the NT 4.0 binary unchanged (no NT5 variant needed):
        # PE subsystem 4.00, the NT4 status string.
        import check_nt4_driver_imports as nt4
        self.assertEqual(nt4.subsystem(SYS), '4.00')
        self.assertIn('usosvbe 1.0-nt4'.encode('utf-16-le'), SYS.read_bytes())


