"""Resolve our Windows NT 4.0 driver builds (AHCINT with AHCI_NT4, usosrst)
against the NT 4.0 SP6a i386 kernel, HALs and ScsiPort, following export
forwarders (same resolver as check_nt52_driver_imports.py).

    python tools/tests/check_nt4_driver_imports.py --sp-iso NT4SP6APL.iso DRIVER.sys [...]
    python tools/tests/check_nt4_driver_imports.py --i386 DIR DRIVER.sys [...]
    python tools/tests/check_nt4_driver_imports.py --sp-iso NT4SP6APL.iso --dump-exports OUT.txt

The SP6a service pack CD (volume NT4SP6APL) carries the expanded I386 files.
Every driver is checked against each kernel (ntoskrnl.exe, ntkrnlmp.exe)
and each HAL that the NT4 profiles can pin (hal.dll, halmps.dll, halapic.dll);
an import counts only when it resolves on all of them.

--dump-exports writes the export names (no code, no data) as a text list.
tools/tests/data/nt4sp6a_exports.txt (SP6a CD) and nt4rtm_exports.txt
(NT 4.0 Workstation PL CD, build 1381.1, the files text-mode Setup runs
with before any service pack) are those lists; --exports FILE checks against
one, and test_nt4_driver_imports.py runs without any Microsoft file.
The --i386 folder needs the plain (expanded) files. Read-only.
"""
from __future__ import annotations
from pathlib import Path
import argparse, json, struct, subprocess, sys, tempfile

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_nt52_driver_imports import SEVEN, pe, resolve  # noqa: E402

# Module name as drivers import it -> file in the SP6a I386 folder.
KERNELS = {'ntoskrnl.exe': 'NTOSKRNL.EXE', 'ntkrnlmp.exe': 'NTKRNLMP.EXE'}
HALS = {'hal.dll': 'HAL.DLL', 'halmps.dll': 'HALMPS.DLL', 'halapic.dll': 'HALAPIC.DLL'}
OTHERS = {'scsiport.sys': 'SCSIPORT.SYS'}
FILES = {**KERNELS, **HALS, **OTHERS}
FIXTURE = Path(__file__).resolve().parent / 'data' / 'nt4sp6a_exports.txt'


def extract(iso: Path, work: Path) -> Path:
    subprocess.run([SEVEN, 'e', '-y', str(iso), *['I386\\' + n for n in FILES.values()], '-o' + str(work)],
                   check=True, stdout=subprocess.DEVNULL)
    return work


def load_tables(i386: Path) -> dict:
    """{file key: exports} with exports = {name: forwarder text or None}."""
    tables = {}
    for key, name in FILES.items():
        path = next(p for p in i386.iterdir() if p.name.lower() == name.lower())
        tables[key] = pe(path)[0]
    return tables


def dump(tables: dict, label: str) -> str:
    out = [f'# NT 4.0 i386 export names ({label}), generated by',
           '# tools/tests/check_nt4_driver_imports.py --dump-exports. Names only;',
           '# "name -> target" marks an export forwarder.']
    for key in FILES:
        out.append(f'[{key}]')
        out += [n if t is None else f'{n} -> {t}' for n, t in sorted(tables[key].items())]
    return '\n'.join(out) + '\n'


def parse(text: str) -> dict:
    tables, cur = {}, None
    for line in text.splitlines():
        if not line or line.startswith('#'):
            continue
        if line.startswith('['):
            cur = tables.setdefault(line[1:-1], {})
            continue
        name, _, target = line.partition(' -> ')
        cur[name] = target or None
    return tables


def check(tables: dict, drivers: list[Path]) -> dict:
    """Per driver and per kernel/HAL pair: imports and unresolved names."""
    report = {}
    for drv in drivers:
        exports, imports = pe(drv)
        combos = {}
        for kname in KERNELS:
            for hname in HALS:
                view = {'ntoskrnl.exe': (tables[kname], []), 'hal.dll': (tables[hname], []),
                        'scsiport.sys': (tables['scsiport.sys'], [])}
                missing = sorted({m for m in (resolve(view, mod, fn) for mod, fn in imports) if m})
                combos[f'{kname}+{hname}'] = missing
        allmissing = sorted({tuple(m) for v in combos.values() for m in v})
        report[drv.name if sum(d.name == drv.name for d in drivers) == 1 else str(drv)] = {'imports': len(imports), 'modules': sorted({m for m, _ in imports}),
                            'subsystem': subsystem(drv), 'missing': [list(m) for m in allmissing], 'by_combo': combos}
    return report


def subsystem(path: Path) -> str:
    """PE subsystem version (NT 4.0 wants 4.00 or lower)."""
    b = path.read_bytes(); p = struct.unpack_from('<I', b, 60)[0]
    major, minor = struct.unpack_from('<HH', b, p + 24 + 48)
    return f'{major}.{minor:02d}'


def main() -> int:
    a = argparse.ArgumentParser()
    g = a.add_mutually_exclusive_group()
    g.add_argument('--sp-iso', type=Path); g.add_argument('--i386', type=Path); g.add_argument('--exports', type=Path)
    a.add_argument('--dump-exports', type=Path); a.add_argument('--label', default='NT4SP6APL CD, I386'); a.add_argument('--json', type=Path)
    a.add_argument('drivers', type=Path, nargs='*')
    a = a.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        if a.sp_iso:
            tables = load_tables(extract(a.sp_iso, Path(tmp)))
        elif a.i386:
            tables = load_tables(a.i386)
        else:
            tables = parse((a.exports or FIXTURE).read_text())
    if a.dump_exports:
        a.dump_exports.write_text(dump(tables, a.label), newline='\n')
        print(f'wrote {a.dump_exports}')
    report = check(tables, a.drivers)
    if a.json:
        a.json.write_text(json.dumps(report, indent=2))
    bad = False
    for k, v in report.items():
        print(f"{k}: subsystem={v['subsystem']} imports={v['imports']} modules={v['modules']} missing={len(v['missing'])} {v['missing']}")
        bad |= bool(v['missing'])
    if bad:
        print('FAIL: unresolved imports on this NT 4.0 source (forwarders followed)')
        return 1
    if report:
        print('PASS: every import resolves on these NT 4.0 kernels and HALs (forwarders followed)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
