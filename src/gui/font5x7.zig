test "lowercase maps to uppercase glyph" {
    const std = @import("std");
    try std.testing.expectEqual(glyph('A'), glyph('a'));
}

test "all printable ASCII characters 32 through 126 have explicit glyph coverage" {
    const std = @import("std");
    var byte: u8 = 32;
    while (byte <= 126) : (byte += 1) {
        const explicit = lookup(byte);
        try std.testing.expect(explicit != null);
        try std.testing.expectEqual(explicit.?, glyph(byte));
    }
}

test "unsupported bytes use the fallback question-mark glyph" {
    const std = @import("std");
    try std.testing.expect(lookup(0) == null);
    try std.testing.expectEqual(fallback_glyph, glyph(0));
    try std.testing.expectEqual(fallback_glyph, glyph('?'));
}
